#include "lib.h"

void    ft_putnbr(int nb)
{
    long    n;
    char    c;
    
    n = nb;
    if (n < 0)
    {
        n= -n;
        write (1, "-", 1);
    }
    if (n >= 10)
        ft_putnbr(n / 10);
    c = (n % 10) + '0';
    write (1, &c, 1);
}